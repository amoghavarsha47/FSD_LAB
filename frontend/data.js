export const formatINR = (amount) =>
  new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(Number(amount) || 0)

export function suggestCategory(title = '') {
  const value = title.toLowerCase()
  if (/book|textbook|notes|notebook|novel|manual/.test(value)) return 'Books & notes'
  if (/laptop|phone|headphone|calculator|charger|electronic|keyboard|mouse|tablet/.test(value)) return 'Electronics'
  if (/chair|desk|table|shelf|shelves|bookshelf|furniture/.test(value)) return 'Furniture'
  if (/lamp|mattress|bucket|mug|hostel|kettle|storage|pillow/.test(value)) return 'Hostel essentials'
  if (/lab|circuit|breadboard|component|goggle|equipment/.test(value)) return 'Lab equipment'
  return 'Other'
}